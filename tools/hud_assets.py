def blit(img, glyph, ox, oy):
    for y, row in enumerate(glyph):
        for x, ch in enumerate(row):
            if ch == "#":
                img.putpixel((ox + x, oy + y), (255, 255, 255, 255))


def ascii_font(glyphs, cell_w, cell_h, name, height, ascent, space):
    """Glyphs for 0x20..0x7F, 16 per row; lowercase reuses the capitals; missing glyphs fall back (\\0)."""
    img = Image.new("RGBA", (16 * cell_w, 6 * cell_h), (0, 0, 0, 0))
    rows = []
    for r in range(6):
        chars = ""
        for c in range(16):
            cp = 0x20 + r * 16 + c
            ch = chr(cp)
            glyph = glyphs.get(ch.upper()) if ch != " " else None
            if glyph is None:
                chars += "\u0000"
                continue
            blit(img, glyph, c * cell_w, r * cell_h)
            chars += ch
        rows.append(chars)
    img.save(ROOT / "textures/font" / f"{name}.png")
    return [{"type": "space", "advances": {" ": space}},
            {"type": "bitmap", "file": f"chromeneon:font/{name}.png", "height": height, "ascent": ascent,
             "chars": rows}]


def accented_font():
    letters = list(ACCENTED)
    letters += [l.lower() for l in letters]
    cell_w, cell_h = 8, 11
    img = Image.new("RGBA", (16 * cell_w, 2 * cell_h), (0, 0, 0, 0))
    rows = ["", ""]
    for i in range(32):
        r, c = divmod(i, 16)
        if i >= len(letters):
            rows[r] += "\u0000"
            continue
        ch = letters[i]
        base, accent = ACCENTED[ch.upper()]
        blit(img, HUD[base], c * cell_w, r * cell_h + 3)
        if accent:
            blit(img, [row.ljust(len(HUD[base][0]), ".")[:len(HUD[base][0])] if len(HUD[base][0]) == 5
                       else row[1:4] for row in ACCENTS[accent]], c * cell_w, r * cell_h)
        else:  # cedilla
            blit(img, ["..##."], c * cell_w, r * cell_h + 10)
        rows[r] += ch
    img.save(ROOT / "textures/font/hud_accented.png")
    return {"type": "bitmap", "file": "chromeneon:font/hud_accented.png", "height": 11, "ascent": 10, "chars": rows}



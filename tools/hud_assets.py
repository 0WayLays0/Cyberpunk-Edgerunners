def derived():
    eye = [list(r) for r in ICONS["EYE"]]
    for i in range(9):
        eye[8 - i][i] = "#"
        if i < 8:
            eye[8 - i][i + 1] = "."
    ICONS["EYE_OFF"] = ["".join(r) for r in eye]
    pick = [list(r) for r in ICONS["HASTE"]]
    for (y, x) in ((5, 5), (5, 8), (6, 6), (6, 7), (7, 6), (7, 7), (8, 5), (8, 8)):
        pick[y][x] = "#"
    ICONS["FATIGUE"] = ["".join(r) for r in pick]


def icons():
    derived()
    names = list(ICONS)
    img = Image.new("RGBA", (16 * 9, 4 * 9), (0, 0, 0, 0))
    for i, name in enumerate(names):
        art = ICONS[name]
        assert len(art) == 9 and all(len(r) == 9 for r in art), name
        blit(img, art, (i % 16) * 9, (i // 16) * 9)
    (ROOT / "textures/gui").mkdir(parents=True, exist_ok=True)
    img.save(ROOT / "textures/gui/hud_icons.png")
    return names


